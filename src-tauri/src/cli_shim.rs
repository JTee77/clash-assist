//! `--cli install-shim`：把一个很小的 sh 包装脚本写到 PATH 目录里，
//! 之后可以直接 `egress-checker discover --client verge`。
//!
//! 安全设计：
//! - 只写 **一个文件** `<dir>/egress-checker`，内容是 `exec "<本二进制>" --cli "$@"`。
//! - 目录：显式 `--dir` 优先；否则 `/usr/local/bin`（存在且当前用户可写时），再否则 `~/.local/bin`（必要时创建）。
//!   **绝不** sudo / 提权。
//! - 目标已存在且**不是**本工具生成的 shim（无标记行）→ 拒绝覆盖（`shim_exists`）。
//! - 原子写：先写临时文件再 rename，权限 0755。

use std::path::{Path, PathBuf};

pub const SHIM_NAME: &str = "egress-checker";
pub const SHIM_MARKER: &str = "# egress-checker-shim: generated by Egress Checker --cli install-shim";

#[derive(Debug, Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ShimResult {
    pub path: String,
    pub dir: String,
    pub target: String,
    /// 新建（false = 覆盖了旧 shim）
    pub created: bool,
    /// dir 是否已在当前进程的 PATH 里
    pub on_path: bool,
    /// target 是否像开发构建（target/debug|release）而非 /Applications 里的正式安装
    pub target_is_dev_build: bool,
}

#[derive(Debug, Clone, serde::Serialize)]
pub struct ShimError {
    pub code: String,
    pub message: String,
}

fn e(code: &str, message: String) -> ShimError {
    ShimError { code: code.into(), message }
}

/// 单引号 sh 字面量（' → '\''）。
pub fn sh_single_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

pub fn shim_script(target: &str) -> String {
    format!(
        "#!/bin/sh\n{SHIM_MARKER}\n# 删除本文件即可卸载。\nexec {} --cli \"$@\"\n",
        sh_single_quote(target)
    )
}

#[cfg(unix)]
fn dir_writable(p: &Path) -> bool {
    use std::ffi::CString;
    use std::os::unix::ffi::OsStrExt;
    if !p.is_dir() {
        return false;
    }
    let Ok(c) = CString::new(p.as_os_str().as_bytes()) else {
        return false;
    };
    unsafe { libc::access(c.as_ptr(), libc::W_OK) == 0 }
}

#[cfg(not(unix))]
fn dir_writable(_p: &Path) -> bool {
    false
}

pub fn path_contains(path_env: &str, dir: &Path) -> bool {
    path_env
        .split(':')
        .filter(|s| !s.is_empty())
        .any(|s| Path::new(s.trim_end_matches('/')) == dir)
}

/// 选择安装目录（不创建）。
pub fn choose_dir(explicit: Option<&str>, home: Option<&Path>) -> Result<PathBuf, ShimError> {
    if let Some(d) = explicit.map(str::trim).filter(|d| !d.is_empty()) {
        let d = if let Some(rest) = d.strip_prefix("~/") {
            home.map(|h| h.join(rest))
                .ok_or_else(|| e("shim_failed", "无法展开 ~：找不到家目录".into()))?
        } else {
            PathBuf::from(d)
        };
        if !d.is_absolute() {
            return Err(e("shim_failed", format!("--dir 需要绝对路径，收到：{}", d.display())));
        }
        return Ok(d);
    }
    let usr = Path::new("/usr/local/bin");
    if dir_writable(usr) {
        return Ok(usr.to_path_buf());
    }
    home.map(|h| h.join(".local/bin"))
        .ok_or_else(|| e("shim_failed", "找不到家目录，请用 --dir 指定安装目录".into()))
}

pub fn is_dev_build(target: &str) -> bool {
    target.contains("/target/debug/") || target.contains("/target/release/")
}

pub fn install_at(dir: &Path, target: &str, path_env: &str) -> Result<ShimResult, ShimError> {
    std::fs::create_dir_all(dir)
        .map_err(|err| e("shim_failed", format!("无法创建目录 {}：{err}", dir.display())))?;
    let dest = dir.join(SHIM_NAME);
    let mut created = true;
    if let Ok(meta) = std::fs::symlink_metadata(&dest) {
        let ours = meta.is_file()
            && std::fs::read_to_string(&dest)
                .map(|s| s.contains(SHIM_MARKER))
                .unwrap_or(false);
        if !ours {
            return Err(e(
                "shim_exists",
                format!("{} 已存在且不是本工具生成的 shim，拒绝覆盖。", dest.display()),
            ));
        }
        created = false;
    }
    let tmp = dir.join(format!(".{SHIM_NAME}.tmp-{}", std::process::id()));
    std::fs::write(&tmp, shim_script(target))
        .map_err(|err| e("shim_failed", format!("写入 {} 失败：{err}", tmp.display())))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(0o755));
    }
    std::fs::rename(&tmp, &dest).map_err(|err| {
        let _ = std::fs::remove_file(&tmp);
        e("shim_failed", format!("写入 {} 失败：{err}", dest.display()))
    })?;
    Ok(ShimResult {
        path: dest.display().to_string(),
        dir: dir.display().to_string(),
        target: target.to_string(),
        created,
        on_path: path_contains(path_env, dir),
        target_is_dev_build: is_dev_build(target),
    })
}

pub fn install(explicit_dir: Option<&str>) -> Result<ShimResult, ShimError> {
    let exe = std::env::current_exe()
        .map_err(|err| e("shim_failed", format!("读不到本程序路径：{err}")))?;
    let exe = std::fs::canonicalize(&exe).unwrap_or(exe);
    let home = dirs::home_dir();
    let dir = choose_dir(explicit_dir, home.as_deref())?;
    let path_env = std::env::var("PATH").unwrap_or_default();
    install_at(&dir, &exe.display().to_string(), &path_env)
}

/// macOS 主版本号（如 14）；读不到 / 非 macOS 为 None。
pub fn macos_version() -> Option<String> {
    if !cfg!(target_os = "macos") {
        return None;
    }
    let out = std::process::Command::new("/usr/bin/sw_vers")
        .arg("-productVersion")
        .output()
        .ok()?;
    let v = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (!v.is_empty()).then_some(v)
}

pub fn major_of(v: &str) -> Option<u32> {
    v.split('.').next()?.trim().parse().ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmpdir(tag: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("ec-shim-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        d
    }

    #[test]
    fn quote_handles_spaces_and_quotes() {
        assert_eq!(sh_single_quote("/A B/x"), "'/A B/x'");
        assert_eq!(sh_single_quote("a'b"), "'a'\\''b'");
        let s = shim_script("/Applications/Egress Checker.app/Contents/MacOS/egress-checker");
        assert!(s.starts_with("#!/bin/sh\n"));
        assert!(s.contains(SHIM_MARKER));
        assert!(s.contains("exec '/Applications/Egress Checker.app/Contents/MacOS/egress-checker' --cli \"$@\""));
    }

    #[test]
    fn install_creates_then_replaces_own_shim() {
        let d = tmpdir("ok");
        let r = install_at(&d, "/x/egress-checker", &format!("/bin:{}", d.display())).unwrap();
        assert!(r.created);
        assert!(r.on_path);
        assert!(!r.target_is_dev_build);
        let r2 = install_at(&d, "/y/target/debug/egress-checker", "/bin").unwrap();
        assert!(!r2.created);
        assert!(!r2.on_path);
        assert!(r2.target_is_dev_build);
        let body = std::fs::read_to_string(d.join(SHIM_NAME)).unwrap();
        assert!(body.contains("/y/target/debug/egress-checker"));
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn install_refuses_foreign_file() {
        let d = tmpdir("foreign");
        std::fs::create_dir_all(&d).unwrap();
        std::fs::write(d.join(SHIM_NAME), "#!/bin/sh\necho other\n").unwrap();
        let err = install_at(&d, "/x", "").unwrap_err();
        assert_eq!(err.code, "shim_exists");
        assert!(std::fs::read_to_string(d.join(SHIM_NAME)).unwrap().contains("other"));
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn choose_dir_rules() {
        let home = Path::new("/Users/u");
        assert_eq!(choose_dir(Some("~/bin"), Some(home)).unwrap(), PathBuf::from("/Users/u/bin"));
        assert_eq!(choose_dir(Some("relative"), Some(home)).unwrap_err().code, "shim_failed");
        let auto = choose_dir(None, Some(home)).unwrap();
        assert!(auto == Path::new("/usr/local/bin") || auto == Path::new("/Users/u/.local/bin"));
    }

    #[test]
    fn version_major() {
        assert_eq!(major_of("13.6.1"), Some(13));
        assert_eq!(major_of("14"), Some(14));
        assert_eq!(major_of(""), None);
        assert!(path_contains("/a:/b/", Path::new("/b")));
    }
}
